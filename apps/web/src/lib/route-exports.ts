import type { ActivityMode } from '@drawtrail/types';
import type { RouteGenerationSuccess } from '@drawtrail/validation';

export type RouteExport = {
  name: string;
  mode: ActivityMode;
  distanceMeters: number;
  geometry: RouteGenerationSuccess['route']['geometry'];
};

export function escapeXml(value: string) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

export function toGpx(route: RouteExport) {
  const points = route.geometry.coordinates
    .map(
      ([longitude, latitude]) =>
        `      <trkpt lat="${latitude}" lon="${longitude}"/>`,
    )
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="DrawTrail" xmlns="http://www.topografix.com/GPX/1/1">
  <metadata><name>${escapeXml(route.name)}</name></metadata>
  <trk>
    <name>${escapeXml(route.name)}</name>
    <type>${route.mode}</type>
    <desc>${(route.distanceMeters / 1000).toFixed(2)} km route generated by DrawTrail</desc>
    <trkseg>
${points}
    </trkseg>
  </trk>
</gpx>`;
}

export function toGeoJson(route: RouteExport) {
  return JSON.stringify(
    {
      type: 'Feature',
      properties: {
        name: route.name,
        activity: route.mode,
        distanceMeters: route.distanceMeters,
        source: 'DrawTrail',
      },
      geometry: route.geometry,
    },
    null,
    2,
  );
}

export function downloadTextFile(
  filename: string,
  content: string,
  mime: string,
) {
  const blob = new Blob([content], { type: mime });
  const href = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = href;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(href);
}

export function safeExportName(value: string) {
  return (
    value
      .trim()
      .normalize('NFKD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-zA-Z0-9-_]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 64) || 'drawtrail-route'
  );
}

export function routePreviewSvg(route: RouteExport) {
  const coordinates = route.geometry.coordinates;
  const bounds = coordinates.reduce<[number, number, number, number]>(
    ([minX, minY, maxX, maxY], [longitude, latitude]) => [
      Math.min(minX, longitude),
      Math.min(minY, latitude),
      Math.max(maxX, longitude),
      Math.max(maxY, latitude),
    ],
    [Infinity, Infinity, -Infinity, -Infinity],
  );
  const [minX, minY, maxX, maxY] = bounds;
  const spanX = Math.max(maxX - minX, 0.00001);
  const spanY = Math.max(maxY - minY, 0.00001);
  const sampleStep = Math.max(1, Math.ceil(coordinates.length / 1200));
  const sampled = coordinates.filter(
    (_, index) => index % sampleStep === 0 || index === coordinates.length - 1,
  );
  const points = sampled.map(
    ([longitude, latitude]) =>
      [
        48 + ((longitude - minX) / spanX) * 704,
        330 - ((latitude - minY) / spanY) * 250,
      ] as const,
  );
  const path = points
    .map(([x, y], index) => `${index === 0 ? 'M' : 'L'} ${x} ${y}`)
    .join(' ');
  const first = points[0]!;
  const last = points.at(-1)!;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="500" viewBox="0 0 800 500">
  <rect width="800" height="500" fill="#f4f6ef"/>
  <text x="48" y="56" fill="#263b2c" font-family="Georgia,serif" font-size="30">${escapeXml(route.name)}</text>
  <text x="48" y="88" fill="#65705f" font-family="Arial,sans-serif" font-size="16">${route.mode.toUpperCase()} · ${(route.distanceMeters / 1000).toFixed(2)} km</text>
  <path d="${path}" fill="none" stroke="#527646" stroke-width="9" stroke-linecap="round" stroke-linejoin="round"/>
  <circle cx="${first[0]}" cy="${first[1]}" r="10" fill="#527646" stroke="#fff" stroke-width="4"/>
  <circle cx="${last[0]}" cy="${last[1]}" r="10" fill="#c36c4b" stroke="#fff" stroke-width="4"/>
  <text x="48" y="456" fill="#65705f" font-family="Arial,sans-serif" font-size="13">Route generated by DrawTrail · © OpenStreetMap contributors</text>
</svg>`;
}

export async function downloadRoutePng(filename: string, route: RouteExport) {
  const svgUrl = URL.createObjectURL(
    new Blob([routePreviewSvg(route)], { type: 'image/svg+xml;charset=utf-8' }),
  );
  try {
    const image = new Image();
    image.src = svgUrl;
    await image.decode();
    const canvas = document.createElement('canvas');
    canvas.width = 1600;
    canvas.height = 1000;
    const context = canvas.getContext('2d');
    if (!context)
      throw new Error('Image export is unavailable in this browser.');
    context.drawImage(image, 0, 0, canvas.width, canvas.height);
    const png = await new Promise<Blob>((resolve, reject) => {
      canvas.toBlob((blob) =>
        blob
          ? resolve(blob)
          : reject(new Error('Could not create the PNG image.')),
      );
    });
    const pngUrl = URL.createObjectURL(png);
    const anchor = document.createElement('a');
    anchor.href = pngUrl;
    anchor.download = filename;
    anchor.click();
    URL.revokeObjectURL(pngUrl);
  } finally {
    URL.revokeObjectURL(svgUrl);
  }
}
